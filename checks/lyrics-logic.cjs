const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const logic = vm.createContext({});
vm.runInContext(fs.readFileSync(process.argv[2], 'utf8').replace(/^\.pragma library\s*/, ''), logic);
const lines = logic.parse('[ar:Test]\n[00:02.50][00:08.125]First\n[00:05]Second\n[00:06.00]\n[bad]ignored\n[00:05.00]Translation');
assert.equal(lines.length, 4);
assert.equal(lines[0].time, 2.5);
assert.equal(lines[1].text, 'Second / Translation');
assert.equal(lines[2].text, '');
assert.equal(lines[3].time, 8.125);
assert.equal(logic.activeIndex(lines, 0), -1);
assert.equal(logic.activeIndex(lines, 2.5), 0);
assert.equal(logic.activeIndex(lines, 5.01), 1);
assert.equal(logic.activeIndex(lines, 6), 2);
assert.equal(logic.activeIndex(lines, 9), 3);
assert.equal(logic.activeIndex(lines, 3), 0, 'backward seek');
assert.equal(logic.activeIndex([], 1), -1);
assert.equal(logic.activeIndex(lines, NaN), -1);
assert.equal(logic.parse('[offset:500]\n[00:02.00]Early')[0].time, 1.5);
assert.equal(logic.parse('[offset:-500]\n[00:02.00]Late')[0].time, 2.5);
assert.equal(logic.parse('plain lyrics').length, 0);
console.log('LRC timestamps, repeats, translations, blank pauses, offsets and forward/backward seeking passed.');

return function(settings)
local c = settings.commands
local mod = "SUPER + "
local function run(key, cmd)
  hl.bind(key, hl.dsp.exec_cmd(cmd))
end
run(mod .. "Return", c.terminal)
run(mod .. "B", c.browser)
run(mod .. "E", c.files)
hl.bind("Super_L", hl.dsp.exec_cmd(c.launcher), { release = true })
hl.bind("Super_R", hl.dsp.exec_cmd(c.launcher), { release = true })
run(mod .. "D", c.desktopToggle)
run(mod .. "W", c.wallpaper)
run(mod .. "M", c.widgets)
run(mod .. "L", c.lock)
run(mod .. "SHIFT + E", c.power)
run(mod .. "SHIFT + S", c.screenshot)
run("Print", c.screenshot)
hl.bind(mod .. "SHIFT + R", function() hl.reload_config() end)
hl.bind(mod .. "Q", hl.dsp.window.close())
hl.bind(mod .. "F", hl.dsp.window.fullscreen({ mode = "fullscreen", action = "toggle" }))
hl.bind(mod .. "Space", hl.dsp.window.float({ action = "toggle" }))
hl.bind(mod .. "P", hl.dsp.window.pseudo({ action = "toggle" }))
hl.bind(mod .. "J", hl.dsp.layout("togglesplit"))
for key, direction in pairs({ left = "left", right = "right", up = "up", down = "down" }) do
  hl.bind(mod .. key, hl.dsp.focus({ direction = direction }))
  hl.bind(mod .. "SHIFT + " .. key, hl.dsp.window.move({ direction = direction }))
end
for i = 1, 9 do
  hl.bind(mod .. tostring(i), hl.dsp.focus({ workspace = tostring(i) }))
  hl.bind(mod .. "SHIFT + " .. tostring(i), hl.dsp.window.move({ workspace = tostring(i), follow = true }))
end
hl.bind(mod .. "mouse:272", hl.dsp.window.drag(), { mouse = true })
hl.bind(mod .. "mouse:273", hl.dsp.window.resize(), { mouse = true })
run("XF86AudioRaiseVolume", c.volume .. " set-volume -l 1.0 @DEFAULT_AUDIO_SINK@ 5%+")
run("XF86AudioLowerVolume", c.volume .. " set-volume @DEFAULT_AUDIO_SINK@ 5%-")
run("XF86AudioMute", c.volume .. " set-mute @DEFAULT_AUDIO_SINK@ toggle")
run("XF86AudioMicMute", c.volume .. " set-mute @DEFAULT_AUDIO_SOURCE@ toggle")
run("XF86MonBrightnessUp", c.brightnessUp)
run("XF86MonBrightnessDown", c.brightnessDown)
run(mod .. "F6", c.brightnessUp)
run(mod .. "F5", c.brightnessDown)
run("XF86AudioPlay", c.media .. " play-pause")
run("XF86AudioNext", c.media .. " next")
run("XF86AudioPrev", c.media .. " previous")
end
